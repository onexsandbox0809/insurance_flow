const BASE = 'https://your-app.vercel.app';

const out = [];
out.push('-- =====================================================================');
out.push('--  Sample data for every table.  Run it ONCE (re-running skips existing rows but repeats the audit log).');
out.push('--  Generated by:  node scripts/make-seed.js > supabase/seed.sql');
