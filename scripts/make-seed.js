const flowNo = { personal: ['full_name', 'dob', 'gender', 'mobile', 'city'], nominee: ['nominee_name', 'nominee_relation'], insured: ['persons', 'p1_name', 'p1_sum_insured'], medical: ['any_condition'], covers: ['covers'] };
