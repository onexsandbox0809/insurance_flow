for (const p of samples) {
  const row = { ...p, created_at: tsOf(p), updated_at: tsOf(p), updated_date: p.entry_date, updated_time: p.entry_time };
  const mine = docs.filter((d) => d[0] === p.proposal_no);
  mine.forEach((d) => { row[colOf[d[1]]] = `${BASE}/d/${d[7]}`; });
  row.flow_personal_at = `${p.entry_date} ${p.entry_time}`;
  if ((p.flows_completed || []).includes('nominee')) row.flow_nominee_at = row.flow_personal_at;
  if ((p.flows_completed || []).includes('insured')) row.flow_insured_at = row.flow_personal_at;
  if ((p.flows_completed || []).includes('medical')) row.flow_medical_at = row.flow_personal_at;
  if ((p.flows_completed || []).includes('covers')) row.flow_covers_at = row.flow_personal_at;
  if ((p.flows_completed || []).includes('documents')) row.flow_documents_at = row.flow_personal_at;
  const cols = Object.keys(row).filter((k) => row[k] !== undefined);
  out.push(`insert into proposals (${cols.join(', ')})`);
  out.push(`values (${cols.map((k) => (k === 'created_at' || k === 'updated_at' ? `${q(row[k])}::timestamptz` : q(row[k]))).join(', ')})`);
  out.push('on conflict (proposal_no) do nothing;');
  out.push('');
}

